def project(lat: float, lon: float, y0: float = 322.28, scale: float = 137.71) -> tuple[float, float]:
    """Projects (lat, lon) onto the Miller Cylindrical SVG canvas."""
    x = 450.0 + lon * (896.0 / 360.0)
    lat_clamped = max(-80.0, min(84.0, lat))
    ym = 1.25 * math.log(math.tan(math.pi / 4 + 0.4 * math.radians(lat_clamped)))
    y = y0 - scale * ym
    return round(x, 1), round(y, 1)


def recompute_all(world_file: Path = WORLD_PATH) -> dict:
    """Reads world_file, recomputes world['c'], writes back, and verifies."""
    world = json.loads(world_file.read_text(encoding="utf-8"))
    orig_c = world.get("c", {})

    missing = [k for k in orig_c if k not in COUNTRY_LAT_LON]
    if missing:
        raise ValueError(f"Missing lat/lon for countries: {missing}")

    updated_c = {}
    for code, (cname, _, _) in orig_c.items():
        lat, lon = COUNTRY_LAT_LON[code]
        x, y = project(lat, lon)
        updated_c[code] = [cname, x, y]

    # Verify all coordinates are within SVG canvas bounds
    for code, (name, x, y) in updated_c.items():
        if not (2.0 <= x <= 898.0):
            raise ValueError(f"Country {code} ({name}) x coordinate {x} out of bounds [2, 898]")
        if not (35.0 <= y <= 480.0):
            raise ValueError(f"Country {code} ({name}) y coordinate {y} out of bounds [35, 480]")

    world["c"] = updated_c
    world_file.write_text(json.dumps(world, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"Successfully recomputed and wrote {len(updated_c)} country coordinates to {world_file}.")
    return updated_c


if __name__ == "__main__":
    recompute_all()
